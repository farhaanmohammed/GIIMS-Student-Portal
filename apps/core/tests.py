from decimal import Decimal

from django.contrib.auth import get_user_model
from django.contrib.auth.models import AnonymousUser
from django.core.exceptions import PermissionDenied
from django.http import HttpResponse
from django.test import RequestFactory, TestCase

from apps.centres.models import Centre
from apps.core.exporters import (
    PdfTableSection,
    build_csv_response,
    build_pdf_document,
    build_pdf_response,
    sanitize_csv_cell,
)
from apps.core.permissions import role_required

User = get_user_model()


@role_required(User.Role.ADMIN, User.Role.MANAGEMENT)
def sample_admin_view(request):
    return HttpResponse("Admin Authorized")


@role_required(User.Role.ACCOUNTS)
def sample_accounts_view(request):
    return HttpResponse("Accounts Authorized")


class CorePermissionTests(TestCase):
    def setUp(self):
        self.factory = RequestFactory()
        self.centre_kochi = Centre.objects.create(code="KC-01", name="Kochi Campus")
        self.admin_user = User.objects.create_user(
            username="test_admin",
            password="Password123!",
            role=User.Role.ADMIN,
        )
        self.admissions_user = User.objects.create_user(
            username="test_admissions",
            password="Password123!",
            role=User.Role.ADMISSIONS,
        )
        self.accounts_user = User.objects.create_user(
            username="test_accounts",
            password="Password123!",
            role=User.Role.ACCOUNTS,
        )

    def test_role_required_permits_authorized_role(self):
        request = self.factory.get("/dummy-admin/")
        request.user = self.admin_user
        response = sample_admin_view(request)
        self.assertEqual(response.status_code, 200)
        self.assertEqual(response.content, b"Admin Authorized")

    def test_role_required_permits_superuser_regardless_of_role(self):
        superuser = User.objects.create_superuser(
            username="test_superuser",
            password="Password123!",
            role=User.Role.ADMISSIONS,
        )
        request = self.factory.get("/dummy-admin/")
        request.user = superuser
        response = sample_admin_view(request)
        self.assertEqual(response.status_code, 200)

    def test_role_required_denies_unauthorized_role(self):
        request = self.factory.get("/dummy-admin/")
        request.user = self.admissions_user
        with self.assertRaises(PermissionDenied):
            sample_admin_view(request)

    def test_role_required_denies_anonymous_user(self):
        request = self.factory.get("/dummy-admin/")
        request.user = AnonymousUser()
        with self.assertRaises(PermissionDenied):
            sample_admin_view(request)


class ExporterSecurityAndPdfTests(TestCase):
    def test_sanitize_csv_cell_prefixes_dangerous_formula_characters(self):
        self.assertEqual(sanitize_csv_cell("=SUM(A1:A5)"), "'=SUM(A1:A5)")
        self.assertEqual(sanitize_csv_cell("+cmd|' /C calc'!A0"), "'+cmd|' /C calc'!A0")
        self.assertEqual(sanitize_csv_cell("-2+3"), "'-2+3")
        self.assertEqual(sanitize_csv_cell("@SUM(1+1)"), "'@SUM(1+1)")
        self.assertEqual(sanitize_csv_cell("\t=1+1"), "'\t=1+1")
        self.assertEqual(sanitize_csv_cell("   =HYPERLINK()"), "'   =HYPERLINK()")

    def test_sanitize_csv_cell_preserves_safe_values_and_negative_decimals(self):
        self.assertEqual(sanitize_csv_cell("Rahul Nair"), "Rahul Nair")
        self.assertEqual(sanitize_csv_cell(Decimal("12500.50")), "12500.50")
        self.assertEqual(sanitize_csv_cell(Decimal("-500.00")), "-500.00")
        self.assertEqual(sanitize_csv_cell(None), "")

    def test_build_csv_response_neutralizes_formulas_and_sets_attachment_headers(self):
        response = build_csv_response(
            filename="ledger_export",
            headers=["Student", "Notes", "Amount"],
            rows=[["=EVIL()", "@attack", Decimal("1500.00")]],
        )
        self.assertEqual(response["Content-Type"], "text/csv; charset=utf-8")
        self.assertIn('attachment; filename="ledger_export.csv"', response["Content-Disposition"])
        body = response.content.decode("utf-8")
        self.assertIn("'=EVIL(),'@attack,1500.00", body)

    def test_build_pdf_document_and_response_generate_valid_pdf_1_4(self):
        pdf_bytes = build_pdf_document(
            title="GIIMS Test Report",
            subtitle="Centre: Kochi (KC-01)",
            metadata=[("Generated By", "accounts_user"), ("Total", "15000.00 INR")],
            sections=[
                PdfTableSection(
                    title="Installments",
                    headers=["Seq", "Description", "Amount"],
                    rows=[[str(i), f"Installment {i}", "1000.00"] for i in range(1, 75)],
                )
            ],
            footer_note="Confidential financial document.",
        )
        self.assertTrue(pdf_bytes.startswith(b"%PDF-1.4\n"))
        self.assertTrue(pdf_bytes.endswith(b"%%EOF\n"))
        self.assertIn(b"/Type /Catalog", pdf_bytes)
        self.assertIn(b"GIIMS Test Report", pdf_bytes)

        response = build_pdf_response(filename="test_report.pdf", pdf_bytes=pdf_bytes)
        self.assertEqual(response["Content-Type"], "application/pdf")
        self.assertIn('attachment; filename="test_report.pdf"', response["Content-Disposition"])
